    ## 1. 문장 성분 쪼개기

    
    **You love me.** 는 **주어 + 동사 + 목적어** 로 이루어진 **3형식 문장**이에요. 아래처럼 성분부터 쪼개면 간단합니다.

    
    | 단어 | 품사 | 성분 | 뜻 |
    |---|---|---|---|
    | You | 대명사 | 주어 S | 너는 |
    | love | 동사 | 동사 V | 사랑한다 |
    | me | 대명사 | 목적어 O | 나를 |

    
    ```structure
    You   love   me.
    [주어 S]   [동사 V]   [목적어 O]
    ```

    
    ## 2. 왜 I가 아니라 me인가요?

    
    영어는 대명사의 **형태**로 역할을 표시해요. 목적어 자리에 오면 단어가 바뀝니다.

    
    | 주격 (주어 자리) | 목적격 (목적어 자리) |
    |---|---|
    | I 나는 | me 나를 |
    | he 그는 | him 그를 |
    | we 우리는 | us 우리를 |
    | you 너는 | you 너를 — 형태가 같음 |

    
